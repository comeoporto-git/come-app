function buildTransactions(): EBTransaction[] {
  return RAW.map(([id, date, type, amount, desc]) => ({
    transaction_id: id,
    transaction_amount: { amount: String(amount), currency: "EUR" },
    credit_debit_indicator: type === "c" ? "CRDT" : "DBIT",
    transaction_date: date,
    booking_date: date,
    ...(type === "d"
      ? { creditor: { name: desc } }
      : { debtor:   { name: desc } }),
    remittance_information: desc,
    status: "BOOK",
  }));
}

export async function GET() {
  try {
    const txns = buildTransactions();

    // Fetch existing transaction_ids to skip already-imported entries
    const existing = await getStoredTransactions(0, 10000);
    const existingIds = new Set(existing.map((t) => t.transaction_id));
    const newTxns = txns.filter((t) => !existingIds.has(t.transaction_id!));

    if (newTxns.length > 0) {
      await upsertBankTransactions(newTxns, ACCOUNT_UID, INSTITUTION);
    }

    return NextResponse.json({ ok: true, inserted: newTxns.length, skipped: txns.length - newTxns.length });
  } catch (e) {
    const msg = e instanceof Error ? e.message : String(e);
    return NextResponse.json({ ok: false, error: msg }, { status: 500 });
  }
}
